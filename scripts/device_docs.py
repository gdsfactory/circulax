"""Generate device pages/notebooks from source docstrings without importing JAX.

Run ``python scripts/device_docs.py --write`` after changing device documentation;
``--check`` rejects stale generated sources, and ``--execute`` runs every example
in an isolated namespace. See docs/writing_components.md for the authoring format.
"""

# ruff: noqa: S102, INP001, TRY301 -- examples are trusted repository code, just like tests.
from __future__ import annotations

import argparse
import ast
import base64
import hashlib
import inspect
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
GUIDE = Path("docs/components/devices.md")
NOTEBOOK = Path("examples/photonic/device_guide.ipynb")
WALKTHROUGH = Path("docs/examples/device_guide.md")
FENCE = re.compile(r"^```python\n(.*?)^```[ \t]*$", re.MULTILINE | re.DOTALL)


@dataclass(frozen=True)
class Device:
    """One opt-in source definition and its executable documentation."""

    name: str
    module: str
    group: str
    reference: str
    prose: str
    examples: tuple[str, ...]
    source: str
    line: int
    revision: str = ""

    @property
    def key(self) -> str:
        """Return the fully qualified source object name."""
        return f"{self.module}.{self.name}"


def _section(doc: str, name: str) -> tuple[str, str]:
    """Remove one indented Google-style metadata section."""
    pattern = re.compile(rf"^{re.escape(name)}:\n((?:[ \t]+[^\n]*\n?|\n)+)", re.MULTILINE)
    matches = list(pattern.finditer(doc))
    if len(matches) != 1:
        msg = f"Expected exactly one {name!r} section"
        raise ValueError(msg)
    match = matches[0]
    value = inspect.cleandoc(match[1]).strip()
    return value, (doc[: match.start()] + doc[match.end() :]).strip()


def _library_revision(root: Path) -> str:
    """Fingerprint implementation sources so physics changes invalidate saved output."""
    revision = hashlib.sha256()
    for source in sorted((root / "circulax").rglob("*.py")):
        if source.name != "_version.py":
            revision.update(source.relative_to(root).as_posix().encode())
            revision.update(source.read_text(encoding="utf-8").encode())
    return revision.hexdigest()


def collect_devices(root: Path = ROOT) -> list[Device]:
    """Read opt-in docstrings with AST; no simulation dependencies are imported."""
    devices = []
    library_revision = _library_revision(root)
    for path in sorted((root / "circulax/components").glob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        for node in tree.body:
            if not isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                continue
            doc = ast.get_docstring(node) or ""
            if not re.search(r"^Device group:$", doc, re.MULTILINE):
                continue
            try:
                group, body = _section(doc, "Device group")
                reference, body = _section(body, "Device reference")
                example_text, prose = _section(body, "Examples")
                examples = tuple(match[1].rstrip() + "\n" for match in FENCE.finditer(example_text))
                if not examples:
                    msg = "Examples needs at least one fenced python block"
                    raise ValueError(msg)
                if not (root / "docs/components" / reference).is_file():
                    msg = f"Device reference does not exist: {reference}"
                    raise ValueError(msg)
                for example in examples:
                    ast.parse(example, filename=f"{path}:{node.name} example")
            except (ValueError, SyntaxError) as exc:
                msg = f"{path}:{node.lineno} ({node.name}): {exc}"
                raise ValueError(msg) from exc
            devices.append(
                Device(
                    node.name,
                    f"circulax.components.{path.stem}",
                    group,
                    reference,
                    prose,
                    examples,
                    path.relative_to(root).as_posix(),
                    node.lineno,
                    library_revision,
                )
            )
    return sorted(devices, key=lambda device: (device.group, device.name))


def render_guide(devices: list[Device]) -> str:
    """Render the generated device guide from the authoritative docstrings."""
    text = [
        "# Devices: choosing and connecting components\n\n",
        "<!-- Generated by scripts/device_docs.py. Edit component docstrings, not this file. -->\n\n",
        (
            "These explanations and executable examples come directly from the device code. "
            "The [photonic notebook walkthrough](../examples/device_guide.md) is generated from the same docstrings.\n\n"
        ),
        (
            "Register component classes or compiled subcircuit objects in `compile_circuit`'s model mapping. "
            "Wire their documented external ports; internal states are solver unknowns. "
            "Netlist builders return topology dictionaries instead. See [Writing components](../writing_components.md) "
            "for authoring instructions.\n\n"
        ),
        (
            "Optical circuits use complex envelopes; use `is_complex=True` and enable float64. "
            "At z0=1 a matched incident field has power `abs(a)**2` W. Under reflection, "
            "total node voltage is not the incident field. See the [shared conventions](photonic_conventions.md). "
            "For mixed-domain small signals use explicit I/Q "
            "[quadrature response](photonics.md#running-examples-and-small-signal-response).\n\n"
        ),
    ]
    group = None
    for device in devices:
        if device.group != group:
            group = device.group
            text.append(f"## {group}\n\n")
        text.extend(
            (
                f"### `{device.name}`\n\n",
                device.prose + "\n\n",
                (
                    f"[Detailed model reference]({device.reference}) · "
                    f"[API and source](../references/components/{device.module.rsplit('.', 1)[-1]}.md#{device.key})\n\n"
                ),
            )
        )
        text.extend(f"```python\n{example}```\n\n" for example in device.examples)
    return "".join(text).rstrip() + "\n"


def make_notebook(devices: list[Device]) -> dict[str, Any]:
    """Build deterministic notebook cells using only photonic device docstrings."""
    cells = []

    def add(kind: str, source: str, origin: str) -> None:
        digest = hashlib.sha256(f"{origin}\n{source}".encode()).hexdigest()
        cell = {"cell_type": kind, "id": digest[:16], "metadata": {"device_source": origin}, "source": source.rstrip()}
        if kind == "code":
            cell.update(execution_count=None, outputs=[])
        cells.append(cell)

    add(
        "markdown",
        "# Photonic devices: generated walkthrough\n\n"
        "Generated from component docstrings by `scripts/device_docs.py`. Edit the device code "
        "and regenerate, rather than editing this notebook. Every example is self-contained. "
        "These illustrative models are not calibrated devices. Detailed model pages record "
        "equations, units, provenance and validation limits.\n\n"
        "Use the Devices guide for electronic models as well. Larger circuit tutorials remain "
        "separate compositions importing these library components.",
        "introduction",
    )
    for device in devices:
        if not device.group.startswith("Photonic"):
            continue
        add("markdown", f"## {device.name}\n\n{device.prose}\n\nSource: `{device.key}`", device.key)
        for example in device.examples:
            prefix = "# Copyright (c) 2026 Circulax contributors\n" if not any(c["cell_type"] == "code" for c in cells) else ""
            add("code", prefix + example, device.key)
    return {
        "cells": cells,
        "metadata": {
            "device_generator": "scripts/device_docs.py",
            "device_library_revision": hashlib.sha256("".join(sorted({d.revision for d in devices})).encode()).hexdigest(),
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def _source(cell: dict[str, Any]) -> str:
    value = cell["source"]
    return "".join(value) if isinstance(value, list) else value


def notebook_matches(actual: dict[str, Any], expected: dict[str, Any]) -> bool:
    """Compare authored structure, allowing kernel outputs and execution metadata."""

    def signature(nb: dict[str, Any]) -> list[tuple[Any, ...]]:
        return [(c["cell_type"], c.get("id"), c.get("metadata", {}).get("device_source"), _source(c).rstrip()) for c in nb["cells"]]

    return signature(actual) == signature(expected) and actual.get("metadata", {}).get("device_library_revision") == expected.get(
        "metadata", {}
    ).get("device_library_revision")


def current_notebook(expected: dict[str, Any], root: Path = ROOT) -> dict[str, Any]:
    """Reuse executed outputs only if all generated source cells still match."""
    path = root / NOTEBOOK
    if path.exists():
        actual = json.loads(path.read_text(encoding="utf-8"))
        if notebook_matches(actual, expected):
            return actual
    return expected


def render_walkthrough(notebook: dict[str, Any]) -> tuple[str, dict[str, bytes]]:
    """Render notebook source and trusted saved outputs without nbconvert/Jupyter."""
    text = ["<!-- Generated by scripts/device_docs.py from component docstrings. -->\n\n"]
    images = {}
    for index, cell in enumerate(notebook["cells"]):
        if cell["cell_type"] == "markdown":
            text.append(_source(cell) + "\n\n")
            continue
        text.append(f"```python\n{_source(cell).rstrip()}\n```\n\n")
        for output_index, output in enumerate(cell.get("outputs", [])):
            if output["output_type"] == "error":
                msg = "Generated notebook contains failed execution outputs; regenerate and execute it"
                raise ValueError(msg)
            if output["output_type"] == "stream":
                value = output.get("text", "")
                value = "".join(value) if isinstance(value, list) else value
                text.append(f"```text\n{value.rstrip()}\n```\n\n")
            elif "image/png" in output.get("data", {}):
                name = f"device_guide_files/device_{index}_{output_index}.png"
                value = output["data"]["image/png"]
                images[name] = base64.b64decode("".join(value) if isinstance(value, list) else value)
                text.append(f"![Device example plot]({name})\n\n")
    return "".join(text).rstrip() + "\n", images


def artifacts(root: Path = ROOT) -> tuple[dict[Path, str], dict[str, Any], dict[str, bytes]]:
    """Produce pages and source notebook, retaining only current execution outputs."""
    devices = collect_devices(root)
    expected = make_notebook(devices)
    notebook = current_notebook(expected, root)
    walkthrough, images = render_walkthrough(notebook)
    return {GUIDE: render_guide(devices), WALKTHROUGH: walkthrough}, expected, images


def generate(root: Path = ROOT, *, check: bool = False) -> None:
    """Write artifacts, or reject stale prose/code without executing any examples."""
    pages, expected, images = artifacts(root)
    stale = [
        str(path) for path, body in pages.items() if not (root / path).exists() or (root / path).read_text(encoding="utf-8") != body
    ]
    notebook_path = root / NOTEBOOK
    if not notebook_path.exists() or not notebook_matches(json.loads(notebook_path.read_text(encoding="utf-8")), expected):
        stale.append(str(NOTEBOOK))
    if check:
        if stale:
            raise ValueError("Stale device documentation: " + ", ".join(stale) + "; run python scripts/device_docs.py --write")
        return
    for path, body in pages.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_text(body, encoding="utf-8")
    if str(NOTEBOOK) in stale:
        notebook_path.parent.mkdir(parents=True, exist_ok=True)
        notebook_path.write_text(json.dumps(expected, indent=1) + "\n", encoding="utf-8")
    for name, data in images.items():
        destination = root / WALKTHROUGH.parent / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)


def execute_examples(devices: list[Device]) -> int:
    """Execute each self-contained example; errors identify its source component."""
    import matplotlib as mpl

    mpl.use("Agg")  # CLI/CI execution is headless; notebook cells retain normal plotting.
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    count = 0
    for device in devices:
        for index, example in enumerate(device.examples):
            filename = f"{device.source}:{device.line} [{device.name} example {index + 1}]"
            try:
                exec(compile(example, filename, "exec"), {"__name__": "__device_example__"})
            except Exception as exc:
                msg = f"Device example failed: {filename}"
                raise RuntimeError(msg) from exc
            count += 1
    return count


def main() -> None:
    """Expose generation, freshness checks and example execution to developers/CI."""
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--execute", action="store_true")
    args = parser.parse_args()
    if args.execute:
        print(f"Executed {execute_examples(collect_devices())} device examples")  # noqa: T201
    else:
        generate(check=args.check)


if __name__ == "__main__":
    main()
